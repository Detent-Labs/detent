#!/bin/sh
# scripts/dev-pod.sh — this checkout's devcontainer pod, through `podman kube play`.
#
#   sh scripts/dev-pod.sh spec   print the Pod spec to stdout; calls no podman
#   sh scripts/dev-pod.sh up     build the app image, write .devcontainer/pod.yaml,
#                                play it when needed, wait until every container
#                                passes its probe
#   sh scripts/dev-pod.sh down   remove the pod; the database volume stays
#
# The pod name and the host ports come from scripts/worktree-env.sh, which
# reads the caller's working directory (see worktree-isolation). The spec is
# generated rather than tracked: its hostPath is absolute, and its ports and
# CORS origins differ per worktree. The containers of one pod share one
# network namespace, so every inter-container address is `localhost`.
#
# POSIX sh only — CI's `sh` is dash.
set -eu

_devpod_here=$(dirname "$0")
# shellcheck disable=SC1091
. "$_devpod_here/worktree-env.sh"

DEV_POD_TOPLEVEL=$(git rev-parse --show-toplevel 2>/dev/null) || DEV_POD_TOPLEVEL=""
if [ -z "$DEV_POD_TOPLEVEL" ]; then
  echo "dev-pod.sh: run it inside a git checkout; git rev-parse --show-toplevel answered nothing" >&2
  exit 1
fi

APP_IMAGE="localhost/$DEV_POD-app:latest"
POD_YAML="$DEV_POD_TOPLEVEL/.devcontainer/pod.yaml"

# A double-quoted YAML scalar. A checkout path may hold a space, a `:` or a
# `#`, and each of those breaks a plain scalar.
q() {
  printf '"%s"' "$(printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g')"
}

spec() {
  cat <<EOF
# Generated by scripts/dev-pod.sh spec. Do not edit; re-run the bring-up.
apiVersion: $(q v1)
kind: $(q Pod)
metadata:
  name: $(q "$DEV_POD")
spec:
  containers:
    - name: $(q app)
      image: $(q "$APP_IMAGE")
      imagePullPolicy: $(q Never)
      # Backgrounds scripts/dev-webhook-sink.ts, then idles. args, not
      # command, so the image's entrypoint still runs. Re-runs on every
      # container start, so the sink survives a stop and start. The probe
      # below proves the runtime answers; it does not check the sink, whose
      # crash surfaces as a refused http.request delivery.
      args: [$(q sh), $(q -c), $(q "bun run scripts/dev-webhook-sink.ts & sleep infinity")]
      workingDir: $(q /workspace)
      env:
        - name: $(q DATABASE_URL)
          value: $(q "postgres://postgres:postgres@localhost:5432/workflow_engine")
        # Both localhost and 127.0.0.1 forms: the manual checklist mandates
        # the second address under Windows.
        - name: $(q CORS_ALLOWED_ORIGINS)
          value: $(q "http://localhost:$PORT_VITE,http://127.0.0.1:$PORT_VITE")
        # The published host port of the dev server; vite.config.ts points
        # its hot-reload client at it.
        - name: $(q PORT_VITE)
          value: $(q "$PORT_VITE")
        # The container sets no AUTH_JWT_SECRET or AUTH_ISSUERS, so the server
        # would refuse to start. This is the written-down opt-in: it disables
        # authentication and trusts X-Actor-Id and X-Actor-Roles verbatim.
        # Devcontainer only; never set it in a deployment that real user data
        # reaches.
        - name: $(q ALLOW_INSECURE_DEV_AUTH)
          value: $(q 1)
        # Mailpit's SMTP listener: no auth, no TLS. The notification.email
        # end-to-end test skips when SMTP_HOST is unset.
        - name: $(q SMTP_HOST)
          value: $(q localhost)
        - name: $(q SMTP_PORT)
          value: $(q 1025)
        - name: $(q SMTP_FROM)
          value: $(q workflow-engine@example.test)
        # The http.request egress policy; unset denies every outbound target.
        # localhost:8080 is scripts/dev-webhook-sink.ts, the target of
        # examples/expense-approval.json's 'book' and 'escalated_review' steps
        # and examples/purchase-requisition.json's 'issue_po' step. A change
        # that points an example or a script at a new host adds it here in the
        # same commit.
        - name: $(q HTTP_ACTION_ALLOWED_HOSTS)
          value: $(q localhost:8080)
        # The sink speaks plain HTTP, which the https: rule would otherwise
        # refuse. Devcontainer only, like ALLOW_INSECURE_DEV_AUTH.
        - name: $(q HTTP_ACTION_ALLOW_INSECURE)
          value: $(q 1)
      ports:
        - containerPort: 3000
          hostPort: $PORT_APP
          hostIP: $(q 127.0.0.1)
        - containerPort: 5173
          hostPort: $PORT_VITE
          hostIP: $(q 127.0.0.1)
      volumeMounts:
        - name: $(q workspace)
          mountPath: $(q /workspace)
      livenessProbe:
        exec:
          command: [$(q bun), $(q --version)]
        periodSeconds: 5
        failureThreshold: 24
    - name: $(q db)
      image: $(q docker.io/library/postgres:latest)
      imagePullPolicy: $(q IfNotPresent)
      # args, not command, so the image's entrypoint still runs initdb on a
      # fresh volume. A runtime GUC override, not an initdb-time default: it
      # takes effect on every start regardless of when the volume was first
      # initialized. Every timestamp column is timestamptz
      # (src/engine/store.ts), an absolute UTC instant either way; this changes
      # only how the server logs and untyped-timestamp casts display.
      args: [$(q postgres), $(q -c), $(q log_timezone=Europe/Zurich), $(q -c), $(q timezone=Europe/Zurich)]
      env:
        - name: $(q POSTGRES_USER)
          value: $(q postgres)
        - name: $(q POSTGRES_PASSWORD)
          value: $(q postgres)
        - name: $(q POSTGRES_DB)
          value: $(q workflow_engine)
        # initdb trusts 127.0.0.1 by default. The app container shares the
        # pod's loopback address, so without this every TCP connection it
        # opens would skip the password check. Applies when initdb runs, on
        # a fresh volume.
        - name: $(q POSTGRES_INITDB_ARGS)
          value: $(q --auth-host=scram-sha-256)
      # Floating image tag on purpose: pre-1.0 tracks the latest release.
      # The mount is the parent of PGDATA, not PGDATA itself, so a major bump
      # lands its own '<major>/docker' subdirectory inside this volume. A
      # mount on '.../data' makes the next major exit 1 at startup; the data
      # is not lost, but the pod will not come up.
      volumeMounts:
        - name: $(q pgdata)
          mountPath: $(q /var/lib/postgresql)
      # TCP on the loopback address: the first-boot init server listens on
      # its Unix socket alone, so this probe ignores it.
      livenessProbe:
        exec:
          command: [$(q pg_isready), $(q -h), $(q 127.0.0.1), $(q -U), $(q postgres)]
        periodSeconds: 5
        failureThreshold: 24
    - name: $(q mailpit)
      image: $(q docker.io/axllent/mailpit:v1.27)
      imagePullPolicy: $(q IfNotPresent)
      # Catches every message notification.email sends; caught mail is not
      # persisted. 1025 is SMTP and stays inside the pod; 8025 is the web
      # interface.
      ports:
        - containerPort: 8025
          hostPort: $PORT_MAILPIT
          hostIP: $(q 127.0.0.1)
      livenessProbe:
        exec:
          command: [$(q /mailpit), $(q readyz)]
        periodSeconds: 5
        failureThreshold: 24
  volumes:
    - name: $(q workspace)
      hostPath:
        path: $(q "$DEV_POD_TOPLEVEL")
        type: $(q Directory)
    - name: $(q pgdata)
      persistentVolumeClaim:
        claimName: $(q "$DEV_POD-pgdata")
EOF
}

up() {
  echo "==> Building $APP_IMAGE"
  podman build -q -t "$APP_IMAGE" -f "$DEV_POD_TOPLEVEL/.devcontainer/Dockerfile" "$DEV_POD_TOPLEVEL/.devcontainer" >/dev/null

  _new_spec=$(spec)
  _replay=""
  if ! podman pod exists "$DEV_POD"; then
    _replay="the pod does not exist"
  elif [ ! -f "$POD_YAML" ] || [ "$(cat "$POD_YAML")" != "$_new_spec" ]; then
    _replay="the spec changed"
  else
    _built=$(podman image inspect --format '{{.Id}}' "$APP_IMAGE")
    _running=$(podman container inspect --format '{{.Image}}' "$DEV_POD-app" 2>/dev/null) || _running=""
    if [ "$_built" != "$_running" ]; then
      _replay="the app image changed"
    fi
  fi
  printf '%s\n' "$_new_spec" > "$POD_YAML"

  if [ -n "$_replay" ]; then
    echo "==> Playing $DEV_POD ($_replay)"
    podman kube play --replace "$POD_YAML" >/dev/null
  elif [ "$(podman pod inspect --format '{{.State}}' "$DEV_POD")" != "Running" ]; then
    echo "==> Starting $DEV_POD"
    podman pod start "$DEV_POD" >/dev/null
  else
    echo "==> $DEV_POD already runs this spec and image"
  fi

  _wait=${DEV_POD_WAIT_SECONDS:-120}
  _deadline=$(( $(date +%s) + _wait ))
  _pending="db mailpit app"
  echo "==> Waiting up to ${_wait}s for every container's probe"
  while :; do
    _still=""
    for _c in $_pending; do
      podman healthcheck run "$DEV_POD-$_c" >/dev/null 2>&1 || _still="$_still $_c"
    done
    _pending=$_still
    [ -z "$_pending" ] && break
    if [ "$(date +%s)" -ge "$_deadline" ]; then
      for _c in $_pending; do
        echo "dev-pod.sh: $DEV_POD-$_c did not pass its probe within ${_wait}s. Its log: podman logs $DEV_POD-$_c" >&2
      done
      exit 1
    fi
    sleep 1
  done
  echo "==> $DEV_POD is healthy"
}

down() {
  podman pod rm -f --ignore "$DEV_POD" >/dev/null
  echo "==> Removed $DEV_POD; the volume $DEV_POD-pgdata stays"
}

case "${1:-}" in
  spec) spec ;;
  up) up ;;
  down) down ;;
  *)
    echo "usage: sh scripts/dev-pod.sh spec|up|down" >&2
    exit 2
    ;;
esac
